    if (!n) n = 1;
    const unit = m[3];
    const ms = unit.startsWith('сек') ? n * 1000 : unit.startsWith('мин') ? n * 60000 : n * 3600000;
    const what = (t.match(/(?:напомни|чтобы)\s+(?:мне\s+)?(.+?)(?:\s+через|$)/) || [])[1];
