  function checkRiddle(t) {
    const r = mem.pendingRiddle;
    if (!r) return null;
    if (/(сдаюсь|не знаю|скажи ответ|какой ответ)/.test(t)) {
      mem.pendingRiddle = null;
      return { text: `Ответ: ${r.say} Хочешь ещё одну?`, emotion: 'happy' };
    }
    mem.pendingRiddle = null;
    if (r.a.some((a) => t.includes(a))) return { text: pick(['Правильно! Ты такой умный! 🎉', 'Верно! Ура! 🎉']), emotion: 'love', bounce: true };
    return { text: `Почти! Правильный ответ: ${r.say} Попробуем ещё?`, emotion: 'surprised' };
  }

  function reply(input) {
    const t = norm(input);
    if (!t) return { text: '...', emotion: 'neutral' };

    const riddle = checkRiddle(t);
    if (riddle) return riddle;

    const timer = tryTimer(t);
    if (timer) return timer;

    const math = tryMath(t);
    if (math) return math;

    for (const rule of rules) {
      const m = t.match(rule.re);
      if (m) {
        const res = rule.fn(t, m);
        if (res) return res;
      }
    }

    // если ещё не знаем имя и человек ответил одним словом после вопроса
    const nm = t.match(/^(?:я\s+)?([а-я-]{2,20})$/);
    if (mem.askedName && !mem.name && nm) {
      mem.name = capitalize(nm[1]);
      store.set('name', mem.name);
      return { text: `${mem.name}, очень приятно! Я запомню 💜 Чем займёмся?`, emotion: 'love' };
    }

    let i;
    do { i = Math.floor(Math.random() * fallbacks.length); } while (i === mem.lastFallback);
    mem.lastFallback = i;
    return { text: fallbacks[i], emotion: 'thinking' };
  }

  function greeting() {
    if (mem.name) return { text: `${greetingByTime()}, ${mem.name}! Я так рад тебя снова видеть 💜`, emotion: 'happy' };
    mem.askedName = true;
    return { text: `${greetingByTime()}! Я Луи, твой маленький друг 🐾 Как тебя зовут?`, emotion: 'happy' };
  }

